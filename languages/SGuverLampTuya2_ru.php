<?php

/**
 * ========================================================================
 *  Словарь шаблонов команд для управления устройством SGuverLampTuya2
 * ========================================================================
 *
 * Данный файл определяет массив $dictionary, содержащий набор регулярных
 * шаблонов, используемых для распознавания текстовых или голосовых команд,
 * связанных с управлением Tuya-лампой:
 *
 *   • яркость (белый свет)
 *   • цветовая температура
 *   • цвет RGB
 *   • яркость цветного света (RGB)
 *   • выбор сцены
 *
 * Каждый ключ в массиве $dictionary описывает определённую категорию команд.
 * Значения — это строки, содержащие части слов или словосочетаний, которые
 * должны приводить к срабатыванию соответствующего действия. 
 * Элементы разделяются символом | (или), что позволяет компакто задавать
 * большой набор вариантов.
 *
 * После определения массива выполняется генерация констант вида:
 *     LANG_<КЛЮЧ>  (например: LANG_SGuverLampTuya2_PATTERN_COLOR)
 *
 * Эти константы используются системой для сопоставления входных команд
 * (текстовых, голосовых, от ботов) с реальными действиями устройства.
 *
 * ------------------------------------------------------------------------
 * Описание ключей словаря:
 * ------------------------------------------------------------------------
 *
 * 1) SGuverLampTuya2_PATTERN_BRIGHTNESS
 *    Шаблоны для управления яркостью белого света.
 *    Распознаваемые примеры:
 *      «яркость», «ярче», «светлее», «тусклее», «приглушить», «уровень».
 *
 * 2) SGuverLampTuya2_PATTERN_TEMPERATURE
 *    Шаблоны для управления цветовой температурой.
 *    Примеры:
 *      «теплый», «холодный», «нейтральный», «синее», «желтый», «прохладный».
 *
 * 3) SGuverLampTuya2_PATTERN_COLOR
 *    Базовые цветовые команды для RGB.
 *    Примеры:
 *      «красный», «зелёный», «синий», «фиолетовый», «оранжевый», «голубой».
 *
 * 4) SGuverLampTuya2_PATTERN_COLOR_BRIGHTNESS
 *    Команды, связанные с яркостью именно цветного света (RGB).
 *    Примеры:
 *      «яркость цвета», «сделай цвет ярче», 
 *      «тусклее цвет», «сделай цвет потемнее», «приглуши цвет».
 *
 * 5) SGuverLampTuya2_PATTERN_SCENE
 *    Команды активации сцен или режимов.
 *    Примеры:
 *      «сцена», «режим», «настройка».
 *
 * ------------------------------------------------------------------------
 * Автоматическая генерация констант:
 * ------------------------------------------------------------------------
 *
 * Для каждого ключа массива создаётся константа вида:
 *
 *     LANG_<KEY> = <значение>
 *
 * Это делается для того, чтобы система могла удобно работать с ключами
 * без необходимости каждый раз обращаться к массиву.
 *
 * Если константа уже определена, она не перезаписывается.
 *
 * ========================================================================
 */

$dictionary = array(

    // Управление яркостью белого света
    'SGuverLampTuya2_PATTERN_BRIGHTNESS' =>
        'ярк|ярч|яркость|светлее|приглуш|тусклее|уровень',

    // Управление цветовой температурой (теплый/холодный белый)
    'SGuverLampTuya2_PATTERN_TEMPERATURE' =>
        'температур|тепл|цвет|холодн|синее|желт|прохладн|нейтрал',

    // Управление цветом RGB
    'SGuverLampTuya2_PATTERN_COLOR' =>
        'красн|зел|син|бел|желт|голуб|пурпур|оранж|фиолет|розов|лайм',

    // Яркость цветного (RGB) света
    'SGuverLampTuya2_PATTERN_COLOR_BRIGHTNESS' =>
        'ярк.*цвет|яркость цвет|цвет ярче|цвет ярк|яркость rgb|яркость цветн|туск.*цвет|приглуш.*цвет|темн.*цвет',

    // Управление сценами / режимами
    'SGuverLampTuya2_PATTERN_SCENE' =>
        'сцен|режим|настройк|'
);

foreach ($dictionary as $k => $v) {
    if (!defined('LANG_' . $k)) {
        @define('LANG_' . $k, $v);
    }
}
